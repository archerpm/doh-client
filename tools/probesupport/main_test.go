func TestRenderGo(t *testing.T) {
	src, err := renderGo("2026-10-16", map[string][]string{"geohide": {"Claude", "Grok"}, "comss": {"ChatGPT"}, "dnsai": nil})
	if err != nil {
		t.Fatal(err)
	}
	s := strings.Join(strings.Fields(string(src)), " ") // gofmt aligns the keys: ignore the spacing
	for _, want := range []string{"Code generated by tools/probesupport; DO NOT EDIT.", "package config", `const SupportTestedAt = "2026-10-16"`, `"comss": {"ChatGPT"},`, `"geohide": {"Claude", "Grok"},`, `"dnsai": {},`} {
		if !strings.Contains(s, want) {
			t.Errorf("generated file lacks %q:\n%s", want, s)
		}
	}
	if strings.Index(s, `"comss"`) > strings.Index(s, `"geohide"`) {
		t.Error("providers must be sorted for a stable diff")
	}
}

func TestServiceCatalogue(t *testing.T) {
	names := map[string]bool{}
	cats := map[string]bool{config.CatAI: true, config.CatAIDev: true, config.CatWork: true, config.CatMedia: true, config.CatSocal: true, config.CatGames: true}
	for _, s := range config.ServiceProbes() {
		if s.Name == "" || len(s.Hosts) == 0 || !cats[s.Category] || names[s.Name] {
			t.Errorf("bad or duplicate service %+v", s)
		}
		names[s.Name] = true
		for _, h := range s.Hosts {
			if d, err := config.NormalizeDomain(h); err != nil || d != h {
				t.Errorf("%s: host %q is not a normalized domain", s.Name, h)
			}
		}
	}
}
