// Command probesupport finds out which services each built-in bypass provider
// really proxies, so the Providers tab can say so. It takes the hosts of the
// service catalogue, of the presets and of GeoHide's published lists, asks every
// provider directly over DoH and compares the answers with ordinary DNS.
//
//	go run ./tools/probesupport -out internal/config/support_data.go
//
// A provider answers a geo-blocked host with an address of its own proxy; those
// addresses are learned from the answers themselves (see learnPool) and a service
// counts as supported when at least half of its hosts resolve to them.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"net/netip"
	"os"
	"sort"
	"strings"
	"sync"
	"time"

	"github.com/archerpm/doh-client/internal/config"
	"github.com/archerpm/doh-client/internal/doh"
	"github.com/archerpm/doh-client/internal/resolver"
	"github.com/miekg/dns"
)

// poolMinApex: an address must be returned for at least this many unrelated
// domains to be taken for a proxy address (the -min-apex flag overrides it).
var poolMinApex = 3

// cdnRanges are published ranges of big CDNs (Cloudflare, Fastly) and of Google:
// sites on them share addresses by nature, so such an address says nothing about
// a proxy even when ordinary DNS happened to show other ranges.
var cdnRanges = func() []netip.Prefix {
	var out []netip.Prefix
	for _, s := range []string{
		// Cloudflare (cloudflare.com/ips-v4)
		"173.245.48.0/20", "103.21.244.0/22", "103.22.200.0/22", "103.31.4.0/22", "141.101.64.0/18", "108.162.192.0/18",
		"190.93.240.0/20", "188.114.96.0/20", "197.234.240.0/22", "198.41.128.0/17", "162.158.0.0/15", "104.16.0.0/13",
		"104.24.0.0/14", "172.64.0.0/13", "131.0.72.0/22",
		// Fastly
		"151.101.0.0/16", "199.232.0.0/16",
		// Google
		"142.250.0.0/15", "172.217.0.0/16", "216.58.192.0/19", "74.125.0.0/16", "64.233.160.0/19", "173.194.0.0/16", "209.85.128.0/17",
	} {
		out = append(out, netip.MustParsePrefix(s))
	}
	return out
}()

func isCDN(a netip.Addr) bool {
	for _, p := range cdnRanges {
		if p.Contains(a) {
			return true
		}
	}
	return false
}

// apexOf approximates the registrable domain: the last two labels.
func apexOf(host string) string {
	labels := strings.Split(host, ".")
	if len(labels) <= 2 {
		return host
	}
	return strings.Join(labels[len(labels)-2:], ".")
}

func prefix16(a netip.Addr) netip.Prefix { p, _ := a.Prefix(16); return p }
func prefix24(a netip.Addr) netip.Prefix { p, _ := a.Prefix(24); return p }

// pool is a provider's learned set of proxy addresses and their /24 networks.
type pool struct {
	addrs map[netip.Addr]bool
	nets  map[netip.Prefix]bool
}

func (p pool) has(a netip.Addr) bool { return p.addrs[a] || p.nets[prefix24(a)] }

// learnPool finds a provider's proxy addresses in its own answers: an IPv4
// address that shows up for at least poolMinApex different domains while the
// ordinary DNS never returns anything from its /16. A CDN address shared by many
// sites is excluded by the second condition (ordinary DNS shows that network too).
func learnPool(answers map[string][]netip.Addr, ref16 map[netip.Prefix]bool) pool {
	apexes := map[netip.Addr]map[string]bool{}
	for host, addrs := range answers {
		for _, a := range addrs {
			if !a.Is4() || a.IsUnspecified() || a.IsPrivate() || isCDN(a) {
				continue
			}
			if apexes[a] == nil {
				apexes[a] = map[string]bool{}
			}
			apexes[a][apexOf(host)] = true
		}
	}
	p := pool{addrs: map[netip.Addr]bool{}, nets: map[netip.Prefix]bool{}}
	for a, set := range apexes {
		if len(set) >= poolMinApex && !ref16[prefix16(a)] {
			p.addrs[a] = true
			p.nets[prefix24(a)] = true
		}
	}
	return p
}

// proxied reports whether any answered address belongs to the pool.
func proxied(addrs []netip.Addr, p pool) bool {
	for _, a := range addrs {
		if a.Is4() && p.has(a) {
			return true
		}
	}
	return false
}

// supports: a service counts when at least half of its hosts are proxied.
func supports(s config.Service, isProxied func(host string) bool) (n int, ok bool) {
	for _, h := range s.Hosts {
		if isProxied(h) {
			n++
		}
	}
	return n, n > 0 && n*2 >= len(s.Hosts)
}

// renderGo writes the generated data file.
func renderGo(date string, support map[string][]string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/probesupport; DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("// SupportTestedAt is the date of the last real support test.\n")
	fmt.Fprintf(&b, "const SupportTestedAt = %q\n\n", date)
	b.WriteString("// testedSupport maps a provider id to the services it was seen proxying.\n")
	b.WriteString("var testedSupport = map[string][]string{\n")
	ids := make([]string, 0, len(support))
	for id := range support {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%q: {", id)
		for i, s := range support[id] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", s)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func udpRef(servers []string, host string) []netip.Addr {
	var out []netip.Addr
	for _, s := range servers {
		q := new(dns.Msg)
		q.SetQuestion(dns.Fqdn(host), dns.TypeA)
		c := &dns.Client{Net: "udp", Timeout: 4 * time.Second}
		m, _, err := c.Exchange(q, s)
		if err != nil || m == nil || m.Rcode != dns.RcodeSuccess {
			continue
		}
		out = append(out, resolver.AddrsOf(m)...)
	}
	return out
}

func fetchText(url string) ([]byte, error) {
	resp, err := (&http.Client{Timeout: 30 * time.Second}).Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 4<<20))
}

func main() {
	out := flag.String("out", "", "write the generated Go data file here (empty: only print)")
	rawOut := flag.String("json", "", "write the raw answers as JSON here")
	date := flag.String("date", time.Now().Format("2006-01-02"), "test date recorded in the data file")
	workers := flag.Int("workers", 8, "parallel DoH queries per provider")
	repeat := flag.Int("repeat", 3, "how many times to ask everything; a host counts as proxied if most runs agree")
	only := flag.String("providers", "", "comma-separated provider ids to ask (default: all bypass providers)")
	flag.IntVar(&poolMinApex, "min-apex", poolMinApex, "domains an address must serve to count as a proxy address")
	flag.Parse()
	wanted := map[string]bool{}
	for _, id := range strings.Split(*only, ",") {
		if id = strings.TrimSpace(id); id != "" {
			wanted[id] = true
		}
	}

	// hosts to ask: service catalogue + presets + GeoHide's published lists
	set := map[string]bool{}
	for _, s := range config.ServiceProbes() {
		for _, h := range s.Hosts {
			set[h] = true
		}
	}
	for _, p := range config.Presets() {
		for _, d := range p.Domains {
			set[d] = true
		}
	}
	geohideHosts := map[string]bool{}
	var geohide config.Provider
	for _, p := range config.BuiltinProviders() {
		if p.ID == "geohide" {
			geohide = p
		}
	}
	for _, l := range geohide.Lists {
		b, err := fetchText(l.URL)
		if err != nil {
			fmt.Fprintln(os.Stderr, "list:", err)
			os.Exit(1)
		}
		for _, d := range config.ParseDomainList(b) {
			set[d] = true
			geohideHosts[d] = true
		}
	}
	hosts := make([]string, 0, len(set))
	for h := range set {
		hosts = append(hosts, h)
	}
	sort.Strings(hosts)
	fmt.Printf("hosts to ask: %d (GeoHide lists: %d)\n", len(hosts), len(geohideHosts))

	// ordinary DNS as the reference
	cfg := config.Default()
	ref16 := map[netip.Prefix]bool{}
	var rmu sync.Mutex
	runPool(hosts, *workers*2, func(h string) {
		addrs := udpRef([]string{"8.8.8.8:53", "1.1.1.1:53"}, h)
		rmu.Lock()
		for _, a := range addrs {
			if a.Is4() {
				ref16[prefix16(a)] = true
			}
		}
		rmu.Unlock()
	})
	fmt.Printf("reference networks (/16): %d\n", len(ref16))

	boot := doh.NewBootstrap(cfg.BootstrapDNS)
	type result struct {
		Rcode string   `json:"rcode"`
		Addrs []string `json:"addrs"`
	}
	var provs []config.Provider
	for _, p := range config.BuiltinProviders() {
		if p.Geo && (len(wanted) == 0 || wanted[p.ID]) {
			provs = append(provs, p)
		}
	}
	// every run asks everything again: a provider that answers differently from
	// run to run (Mafioznik does) counts a host only if most runs agree
	var runs []map[string]map[string][]netip.Addr
	var raw map[string]map[string]result
	for run := 0; run < *repeat; run++ {
		raw = map[string]map[string]result{}
		answers := map[string]map[string][]netip.Addr{}
		var wg sync.WaitGroup
		var mu sync.Mutex
		for _, p := range provs {
			wg.Add(1)
			go func() {
				defer wg.Done()
				up, err := doh.New(doh.Options{ID: p.ID, URL: p.URL, Bootstrap: p.Bootstrap, UseGET: p.UseGET, Resolver: boot, Timeout: 6 * time.Second})
				if err != nil {
					fmt.Fprintf(os.Stderr, "%s: %v\n", p.ID, err)
					return
				}
				defer up.Close()
				mine := map[string][]netip.Addr{}
				myRaw := map[string]result{}
				var pm sync.Mutex
				runPool(hosts, *workers, func(h string) {
					var m *dns.Msg
					var err error
					for try := 0; try < 4; try++ {
						q := new(dns.Msg)
						q.SetQuestion(dns.Fqdn(h), dns.TypeA)
						ctx, cancel := context.WithTimeout(context.Background(), 8*time.Second)
						m, err = up.Exchange(ctx, q)
						cancel()
						if err == nil && m != nil {
							break
						}
					}
					pm.Lock()
					defer pm.Unlock()
					if err != nil || m == nil {
						myRaw[h] = result{Rcode: "ERROR"}
						return
					}
					addrs := resolver.AddrsOf(m)
					r := result{Rcode: dns.RcodeToString[m.Rcode]}
					for _, a := range addrs {
						r.Addrs = append(r.Addrs, a.String())
					}
					myRaw[h] = r
					mine[h] = addrs
				})
				mu.Lock()
				answers[p.ID], raw[p.ID] = mine, myRaw
				mu.Unlock()
			}()
		}
		wg.Wait()
		runs = append(runs, answers)
	}

	support := map[string][]string{}
	for _, p := range provs {
		// pool of the last run (for the report) and the per-host majority over all runs
		pl := learnPool(runs[len(runs)-1][p.ID], ref16)
		var poolIPs []string
		for a := range pl.addrs {
			poolIPs = append(poolIPs, a.String())
		}
		sort.Strings(poolIPs)
		votes := map[string]int{}
		for _, ra := range runs {
			plr := learnPool(ra[p.ID], ref16)
			for h, addrs := range ra[p.ID] {
				if proxied(addrs, plr) {
					votes[h]++
				}
			}
		}
		isProxied := func(h string) bool { return votes[h]*2 > len(runs) }
		errs, ghProxied := 0, 0
		for _, r := range raw[p.ID] {
			if r.Rcode == "ERROR" {
				errs++
			}
		}
		for h := range geohideHosts {
			if isProxied(h) {
				ghProxied++
			}
		}
		var names []string
		for _, s := range config.ServiceProbes() {
			if _, ok := supports(s, isProxied); ok {
				names = append(names, s.Name)
			}
		}
		support[p.ID] = names
		fmt.Printf("\n== %s: %d proxy addresses, %d errors, GeoHide-list hosts proxied: %d of %d\n   pool: %s\n   services (%d): %s\n",
			p.ID, len(poolIPs), errs, ghProxied, len(geohideHosts), strings.Join(poolIPs, " "), len(names), strings.Join(names, ", "))
	}

	if *rawOut != "" {
		b, _ := json.MarshalIndent(raw, "", " ")
		if err := os.WriteFile(*rawOut, b, 0o600); err != nil {
			fmt.Fprintln(os.Stderr, err)
		}
	}
	if *out != "" {
		src, err := renderGo(*date, support)
		if err != nil {
			fmt.Fprintln(os.Stderr, "render:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(*out, src, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("\nwritten", *out)
	}
}

// runPool calls fn for every item with at most n calls in flight.
func runPool(items []string, n int, fn func(string)) {
	if n < 1 {
		n = 1
	}
	ch := make(chan string)
	var wg sync.WaitGroup
	for i := 0; i < n; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for it := range ch {
				fn(it)
			}
		}()
	}
	for _, it := range items {
		ch <- it
	}
	close(ch)
	wg.Wait()
}
