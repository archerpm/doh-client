// Command probesupport finds out which services each built-in bypass provider
// really proxies, so the Providers tab can say so. It takes the hosts of the
// service catalogue, of the presets and of GeoHide's published lists, asks every
// provider directly over DoH and compares the answers with ordinary DNS (the
// logic lives in internal/support, which the service also uses for the check
// run from the Providers tab).
//
//	go run ./tools/probesupport -out internal/config/support_data.go
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/archerpm/doh-client/internal/config"
	"github.com/archerpm/doh-client/internal/support"
)

// renderGo writes the generated data file.
func renderGo(date string, tested map[string][]string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/probesupport; DO NOT EDIT.\n\npackage config\n\n")
	b.WriteString("// SupportTestedAt is the date of the last real support test.\n")
	fmt.Fprintf(&b, "const SupportTestedAt = %q\n\n", date)
	b.WriteString("// testedSupport maps a provider id to the services it was seen proxying.\n")
	b.WriteString("var testedSupport = map[string][]string{\n")
	ids := make([]string, 0, len(tested))
	for id := range tested {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%q: {", id)
		for i, s := range tested[id] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", s)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func fetchText(url string) ([]byte, error) {
	resp, err := (&http.Client{Timeout: 30 * time.Second}).Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 4<<20))
}

func main() {
	out := flag.String("out", "", "write the generated Go data file here (empty: only print)")
	rawOut := flag.String("json", "", "write the raw answers as JSON here")
	date := flag.String("date", time.Now().Format("2006-01-02"), "test date recorded in the data file")
	workers := flag.Int("workers", 8, "parallel DoH queries per provider")
	repeat := flag.Int("repeat", 3, "how many times to ask everything; a host counts as proxied if most runs agree")
	only := flag.String("providers", "", "comma-separated provider ids to ask (default: all bypass providers)")
	minApex := flag.Int("min-apex", support.PoolMinApex, "domains an address must serve to count as a proxy address")
	flag.Parse()
	wanted := map[string]bool{}
	for _, id := range strings.Split(*only, ",") {
		if id = strings.TrimSpace(id); id != "" {
			wanted[id] = true
		}
	}

	// extra hosts to ask: presets + GeoHide's published lists
	var extra []string
	for _, p := range config.Presets() {
		extra = append(extra, p.Domains...)
	}
	geohideHosts := map[string]bool{}
	var geohide config.Provider
	var provs []config.Provider
	for _, p := range config.BuiltinProviders() {
		if p.ID == "geohide" {
			geohide = p
		}
		if p.Geo && (len(wanted) == 0 || wanted[p.ID]) {
			provs = append(provs, p)
		}
	}
	for _, l := range geohide.Lists {
		b, err := fetchText(l.URL)
		if err != nil {
			fmt.Fprintln(os.Stderr, "list:", err)
			os.Exit(1)
		}
		for _, d := range config.ParseDomainList(b) {
			extra = append(extra, d)
			geohideHosts[d] = true
		}
	}
	o := support.Options{Services: config.ServiceProbes(), Extra: extra, Providers: provs,
		Bootstrap: config.Default().BootstrapDNS, Repeat: *repeat, Workers: *workers, MinApex: *minApex}
	fmt.Printf("hosts to ask: %d (GeoHide lists: %d)\n", len(o.Hosts()), len(geohideHosts))
	results, err := support.Run(context.Background(), o)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	tested := map[string][]string{}
	raw := map[string]map[string]support.RawAnswer{}
	for _, r := range results {
		ghProxied := 0
		for h := range geohideHosts {
			if r.Proxied(h) {
				ghProxied++
			}
		}
		tested[r.Provider], raw[r.Provider] = r.Services, r.Raw
		fmt.Printf("\n== %s: %d proxy addresses, %d errors, GeoHide-list hosts proxied: %d of %d\n   pool: %s\n   services (%d): %s\n",
			r.Provider, len(r.Pool), r.Errors, ghProxied, len(geohideHosts), strings.Join(r.Pool, " "), len(r.Services), strings.Join(r.Services, ", "))
	}

	if *rawOut != "" {
		b, _ := json.MarshalIndent(raw, "", " ")
		if err := os.WriteFile(*rawOut, b, 0o600); err != nil {
			fmt.Fprintln(os.Stderr, err)
		}
	}
	if *out != "" {
		src, err := renderGo(*date, tested)
		if err != nil {
			fmt.Fprintln(os.Stderr, "render:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(*out, src, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		fmt.Println("\nwritten", *out)
	}
}
